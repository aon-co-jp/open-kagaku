//! open-kagaku: OTC(市販)医薬品有効成分・漢方処方の参考データベースと、
//! 風邪薬(漢方+化学薬品ハイブリッド)配合の一次スクリーニングツール。
//!
//! # ⚠️ 最重要制約(必ず全ドキュメント・コード・UIに一貫して明記すること)
//!
//! **本クレートは医療機器・医薬品ソフトウェアではなく、教育・研究・
//! 設計検討用の参考ツールに過ぎない。実際の服薬判断・処方・製剤設計には
//! 薬剤師・医師等の有資格者によるレビューが必須であり、本クレートの
//! 出力を根拠に服薬量を決定してはならない。**
//!
//! # スコープ(ユーザー指示に基づく安全な範囲への限定)
//!
//! 開発着手時、ユーザーから「猛毒から毒性を取り除く機能」を含む提案が
//! あったが、これは化学兵器・違法薬物の無毒化/精製手順の生成に転用され
//! 得るデュアルユースリスクがあるため**実装しないことを確認済み**
//! (`AskUserQuestion`でユーザーからも「毒性除去機能は実装しない」旨の
//! 明示的な合意を得た、2026-08-25)。本クレートが扱うのは以下の
//! **安全な範囲のみ**:
//!
//! 1. **化学式表示**(`molecular_formula`): 市販薬の有効成分名から
//!    分子式を引く、教育目的の参考データベース(合成・精製手順は含まない)。
//! 2. **OTC医薬品有効成分DB**(`otc_ingredient`): 一般的な市販薬有効成分
//!    (鎮痛解熱薬・抗ヒスタミン薬・鎮咳薬・去痰薬・鼻炎薬等)の分類・
//!    参考情報。
//! 3. **漢方処方DB**(`kampo_formula`): 公開されている伝統的処方名・
//!    構成生薬・伝統的適応の参考情報(現代医学的な効能を保証するもの
//!    ではない)。
//! 4. **風邪薬配合シミュレーター**(`cold_medicine_formulation`):
//!    化学薬品有効成分+漢方処方を組み合わせた「配合案」を構成し、
//!    同一薬効分類の重複(過量摂取リスクの初歩的な目安)を検出する
//!    一次スクリーニングのみ(実際の相互作用・薬物動態計算は行わない)。
//!
//! いずれのモジュールも`cg-cad-core`の`zoning`/`structural`と同じ設計
//! 思想(ユーザー入力ベース、自動取得はしない、簡易近似であることを
//! 常に明記、動くふりをしない)を踏襲する。

